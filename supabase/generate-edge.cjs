function write(p,s) { fs.writeFileSync(path.join(out,p),s); }
function esm(s) {
 return s.replace(/'use strict';\n/, '')
 .replace(/const crypto = require\('node:crypto'\);/g,"import crypto from 'node:crypto';\nimport {Buffer} from 'node:buffer';")
 .replace(/const \{HttpError\} = require\('\.\/commerce'\);/,"import {HttpError} from './commerce.js';")
 .replace(/module\.exports\s*=\s*(\{[^;]+\});/, 'export $1;');
}
